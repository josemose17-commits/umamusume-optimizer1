// What each skill is worth in a full field: every skill a running style can use on a cup, raced in
// a field of 9 with and without it, on the same gate draws and seeds (paired), on GlobalSim
// (vendor/globalsim, the full-field simulator the Skill optimizer's "for winning" check uses).
// The Umalator's skill chart (data/skillvalues) races one runner against a pacer, so skills that
// depend on other runners (passing, blocking, position, debuffs) are guessed there; here they meet
// a real pack.
//   Her: the cup's stat line (stamina at her style's full-spurt reference, data/stamina-needs.js),
//     A aptitudes, Normal mood, no unique, and a typical build: her style's best chart skills, as a
//     rival of her style has (alone, with no skills, she ran 8th-9th of 9 and position skills
//     fired as for the back of the pack). Each skill is valued against that build: added to it; if
//     it's in it, by taking it out; a tier of a skill in it (a gold over its white) as the tier in
//     it plus the change from swapping it in.
//   The field (modeled): CM's style mix (field-race.js MIX), each rival at the cup's stat line
//     with stamina at her own style's reference, A aptitudes, and her style's best chart skills
//     the cup has (no debuffs, about a finished uma's SP at hint Lv2), as the Skill optimizer's
//     modeled field.
//   Every skill on 400 races (20 gate draws), then the 60 best of each style on 1,200 more.
//   A race where the skill didn't fire counts 0 (it did nothing; the rest is reshuffled rolls).
//   Per skill: L, the lengths she gains (her finish time saved × her speed over the last 200 m,
//     / 2.5 m), with its 95% interval; how often it fires; where (the 10th, 50th and 90th
//     percentile of her position when it fires, in m); her place and win rate gained. A debuff
//     slows rivals rather than her, so its L is the place it gains, at the field's lengths per
//     place (fitted on the other skills: place gained per length gained).
//   --stats: +50 of each stat (stamina past her need is left out) raced the same way, against the
//     solo stat curves (data/stat-curves.js) at the cup's line: field L per solo L, so the app
//     keeps stats (solo curves) and skills (field) on one scale.
// Usage: node tools/build_field_skills.mjs cm22 [--style Senkou] [--races 400] [--part f]
//        node tools/build_field_skills.mjs cm22 --stats [--style Senkou] --part f
//        node tools/build_field_skills.mjs --merge f1 f2 ...   (writes data/field-skills.js)
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(path.join(ROOT, "x.js"));
const F = require(path.join(ROOT, "field-race.js"));
const P = require(path.join(ROOT, "data/presets.js"));
const SO = require(path.join(ROOT, "skill-opt.js"));
const SB = require(path.join(ROOT, "skill-budget.js"));
const family = (id) => ((SB.DATA.skills[String(id)] || [String(id)])[0]);
const PR = require(path.join(ROOT, "parent-relevance.js"));
const POS = require(path.join(ROOT, "data/skill-positions.js"));
const NEEDS = require(path.join(ROOT, "data/stamina-needs.js"));
const DEBUFFS = require(path.join(ROOT, "data/debuffs.js"));
const SV = require(path.join(ROOT, "data/skillvalues/index.js"));
const REL = require(path.join(ROOT, "skill-release.js"));
const TODAY = new Date().toISOString().slice(0, 10);
// Out on Global for the cup, by the app's rule (skill-release.js): the pinned Global catalog
// (data/race-skills.json) lags behind Global's skill list.
const outFor = (p) => { const cut = REL.cutoff(p, TODAY); return (id) => REL.outBy(SV.skills[String(id)], cut); };
const GS = path.join(ROOT, "vendor/globalsim");
const STYLES = ["Nige", "Senkou", "Sasi", "Oikomi"];
const VERSION = 1, DRAWS = 20, SP = 1200, LENGTH = 2.5, TOP = 60, MORE = 1200;

const args = process.argv.slice(2);
const opt = (k, d) => { const i = args.indexOf(k); return i >= 0 ? args[i + 1] : d; };

function write(cups, meta) {
  fs.writeFileSync(path.join(ROOT, "data/field-skills.js"), `// Generated by tools/build_field_skills.mjs. Do not edit.
// Skills raced in a full field with and without each one (see meta.rule). skills: { id: [L, ci95,
// fire share, position p10, p50, p90 (m), place gained, win share gained, kind (0 skill, 1 debuff)] }.
(function (root) {
  const data = ${JSON.stringify({ meta, cups })};
  if (typeof module !== "undefined" && module.exports) module.exports = data;
  else root.UmaFieldSkills = data;
})(typeof window !== "undefined" ? window : globalThis);
`);
}
const META = (o) => ({ version: VERSION, built: new Date().toISOString().slice(0, 10), engine: "GlobalSim v77 (vendor/globalsim)", races: o.races, draws: DRAWS, field: 9,
  rule: "each skill raced with and without it on the same gate draws and seeds, in a field of 9: her at the cup's stat line (stamina at her style's full-spurt reference), A aptitudes, Normal mood, no unique, with her style's best chart skills (the skill added, or taken out if it's one of them; a tier of one of them swapped in); every skill on 400 races, the 60 best per style on 1,200 more; a race where the skill didn't fire counts 0; the rivals in CM's style mix, each at the cup's line (stamina at her style's reference), A aptitudes, with her style's best chart skills (no debuffs, about 1,200 SP at hint Lv2). L: finish time saved × her speed over the last 200 m / 2.5 m; a debuff's L is the place it gains at the field's lengths per place" });

if (args[0] === "--merge") {
  let cups = {};
  try { cups = Object.assign({}, require(path.join(ROOT, "data/field-skills.js")).cups); } catch (e) { cups = {}; }
  let races = 0;
  args.slice(1).forEach((f) => {
    const part = JSON.parse(fs.readFileSync(f, "utf8"));
    races = part.races || races;
    Object.entries(part.cups).forEach(([id, c]) => {
      cups[id] = cups[id] || { course: c.course, styles: {} };
      Object.entries(c.styles).forEach(([st, v]) => { cups[id].styles[st] = Object.assign(cups[id].styles[st] || {}, v); });
    });
  });
  // Debuffs: place gained → lengths, at the field's place gained per length (fitted per style on
  // the other skills, through the origin).
  Object.values(cups).forEach((c) => Object.values(c.styles).forEach((s) => {
    const own = Object.values(s.skills).filter((x) => x[8] === 0 && x[2] > 0.05);
    const sxy = own.reduce((n, x) => n + x[0] * x[6], 0), sxx = own.reduce((n, x) => n + x[0] * x[0], 0);
    s.placePerL = sxx > 0 ? +(sxy / sxx).toFixed(4) : null;
    Object.values(s.skills).forEach((x) => { if (x[8] === 1 && s.placePerL > 0) { x[0] = +(x[6] / s.placePerL).toFixed(3); x[1] = +(x[1] / s.placePerL).toFixed(3); } });
  }));
  write(cups, META({ races }));
  process.exit(0);
}

const E = await import(path.join(GS, "engine.js"));
await E.init(fs.readFileSync(path.join(GS, "wasm/globalsim_bg.wasm")));
const TABLE = JSON.parse(fs.readFileSync(path.join(GS, "skill-data.json"), "utf8")).skills;
const SETTINGS = JSON.parse(fs.readFileSync(path.join(GS, "settings.json"), "utf8"));
const RACES = +opt("--races", 400), PER = Math.max(1, Math.round(RACES / DRAWS));
const cupIds = args.filter((a, i) => !a.startsWith("--") && !(i > 0 && args[i - 1].startsWith("--")));
const onlyStyle = opt("--style", null), part = opt("--part", null), limit = +opt("--limit", 0);

const chart = (id, st) => { try { return require(path.join(ROOT, "data/skillvalues", id + ".json"))[st] || []; } catch (e) { return []; } };
const need = (p, st) => { const r = ((NEEDS.cups[p.id] || {}).styles || {})[st]; return Math.max(p.stats.stamina, r && r.status === "ok" ? r.need : 0); };
const lineFor = (p, st) => ({ speed: p.stats.speed, stamina: need(p, st), power: p.stats.power, guts: p.stats.guts, wisdom: p.stats.wisdom });
// Her style's best chart skills (no debuffs, ones her style can fire from its place), within SP.
function rivalSkills(p, st) {
  const vals = {};
  chart(p.id, st).forEach(([id, med]) => { if (med > 0) vals[String(id)] = med / 100; });
  const out = outFor(p);
  const ids = Object.keys(vals).filter((id) => TABLE[id] && out(id) && !DEBUFFS[id] && PR.positionFits(POS, id, st)).sort((a, b) => vals[b] - vals[a]).slice(0, 16);
  return SO.quickPlan({ skills: ids.map((id) => ({ id, hint: 2 })), values: vals, sp: SP, fast: false }).selected.map((x) => x.id);
}
// Her position at time t, from the replay's frames (linear between frames).
function posAt(rep, t) {
  const w = rep.width, f = rep.frames;
  let prevT = f[0], prevX = f[1];
  for (let i = 1; i < rep.count; i++) {
    const ti = f[i * w], xi = f[i * w + 1];
    if (ti >= t) return prevX + (xi - prevX) * (t - prevT) / Math.max(1e-9, ti - prevT);
    prevT = ti; prevX = xi;
  }
  return prevX;
}
// Her speed over the last 200 m (m/s), from the replay.
function endSpeed(rep, dist) {
  const w = rep.width, f = rep.frames, xs = [];
  for (let i = 0; i < rep.count; i++) { const x = f[i * w + 1], v = f[i * w + 2]; if (x >= dist - 200 && x <= dist && v > 0) xs.push(v); }
  return xs.length ? xs.reduce((a, b) => a + b, 0) / xs.length : null;
}
const q = (xs, k) => { if (!xs.length) return null; const s = xs.slice().sort((a, b) => a - b); return s[Math.min(s.length - 1, Math.floor(k * (s.length - 1) + 0.5))]; };
const summary = (xs) => { const n = xs.length, m = n ? xs.reduce((a, b) => a + b, 0) / n : 0, sd = n > 1 ? Math.sqrt(xs.reduce((t, x) => t + (x - m) * (x - m), 0) / (n - 1)) : 0; return { m, ci: n > 1 ? 1.96 * sd / Math.sqrt(n) : 0, sd }; };

// A part file is also the checkpoint: a restarted run keeps the skills it has (and the ones that
// had their extra races) and goes on from there.
let saved = null;
try { if (part && fs.existsSync(part)) saved = JSON.parse(fs.readFileSync(part, "utf8")); } catch (e) { saved = null; }
const out = { races: RACES, cups: {} }, t0 = Date.now();
const checkpoint = () => { if (part) fs.writeFileSync(part + ".tmp", JSON.stringify(out)), fs.renameSync(part + ".tmp", part); };
for (const id of cupIds.length ? cupIds : ["cm22"]) {
  const p = P.list.find((x) => x.id === id);
  if (!p) throw new Error("no cup " + id);
  const geo = path.join(GS, "course_geometry", p.course.id + ".json");
  if (!fs.existsSync(geo)) { process.stderr.write(id + ": no course geometry\n"); continue; }
  E.registerCourseGeometry(p.course.id, fs.readFileSync(geo, "utf8"));
  const showdown = p.kind === "loh" || (p.no >= 27 && p.kind === "cm");
  const draws = F.layouts(9, DRAWS);
  const rivals = [];
  Object.entries(F.MIX.cm).forEach(([st, n]) => { const skills = rivalSkills(p, st); for (let i = 0; i < n; i++) rivals.push({ style: st, stats: lineFor(p, st), apt: ["A", "A", "A"], mood: 0, skills }); });
  const cup = out.cups[id] = { course: { id: p.course.id, distance: p.course.distance }, styles: {} };
  const race = new E.PreparedRace(F.request({ preset: p, table: TABLE, settings: SETTINGS, showdown }, [F.runner({ style: "Senkou", stats: lineFor(p, "Senkou"), apt: ["A", "A", "A"], skills: [] })].concat(rivals.map(F.runner)), draws[0]));
  for (const st of STYLES) {
    if (onlyStyle && st !== onlyStyle) continue;
    const her = { style: st, stats: lineFor(p, st), apt: ["A", "A", "A"], mood: 0 };
    const build = rivalSkills(p, st), inBuild = new Map(build.map((x) => [family(x), x]));
    // Her races with this skill set, on a seed block: [{ t, place, v, at: { id: position } }].
    const memo = new Map();
    const run = (skills, block) => {
      const key = skills.slice().sort().join(".") + "|" + block;
      if (memo.has(key)) return memo.get(key);
      const per = block ? Math.round(MORE / DRAWS) : PER, res = [];
      draws.forEach((g, gi) => {
        race.prepare(F.request({ preset: p, table: TABLE, settings: SETTINGS, showdown }, [F.runner(Object.assign({}, her, { skills }))].concat(rivals.map(F.runner)), g));
        for (let s = 1; s <= per; s++) {
          const rep = race.run(block * 100000 + gi * 1000 + s), m = rep.metadata, me = m.results[0], at = {};
          (m.skillEvents || []).forEach((e) => { if (e.horseIndex === 0 && at[e.skillId] == null) at[e.skillId] = posAt(rep, e.t); });
          res.push({ t: me.finishTimeRaw, place: me.finishOrder, v: endSpeed(rep, p.course.distance), at });
        }
      });
      memo.set(key, res);
      return res;
    };
    const without = (x) => build.filter((y) => y !== x);
    // Per race: [L, place, win] of a against b (a better: positive), at b's end speed.
    const diff = (a, b) => a.map((x, i) => [(b[i].t - x.t) * (b[i].v || p.course.distance / b[i].t) / LENGTH, b[i].place - x.place, (x.place === 0 ? 1 : 0) - (b[i].place === 0 ? 1 : 0)]);
    const add = (u, v) => u.map((x, i) => x.map((n, j) => n + v[i][j]));
    // A skill's paired gains on one block, and the runs it fired in (its positions). In a race
    // where it didn't fire it did nothing: any difference there is the race's random rolls
    // reshuffled by having one more skill (every never-firing skill showed the same +0.2 places),
    // so those races count 0.
    function value(sid, block) {
      const base = run(build, block), mine = inBuild.get(family(sid));
      let d, fired;
      if (mine === sid) { d = diff(base, run(without(sid), block)); fired = base; }
      else if (mine) { fired = run(without(mine).concat(sid), block); d = add(diff(base, run(without(mine), block)), diff(fired, base)); }
      else { fired = run(build.concat(sid), block); d = diff(fired, base); }
      return { d: d.map((x, i) => (fired[i].at[sid] != null ? x : [0, 0, 0])), fired };
    }
    if (args.includes("--stats")) {
      // Field L of +50 in each stat, paired on 1,600 races, and the solo curve's L for the same.
      const C = require(path.join(ROOT, "data/stat-curves.js")), O = require(path.join(ROOT, "optimizer.js"));
      const rv = O.raceValuesFor(C, id, st), keys = ["speed", "stamina", "power", "guts", "wisdom"], stats = [];
      const runStats = (bump, block) => { const save = her.stats; her.stats = Object.assign({}, save, bump); memo.clear(); const r = run(build, block); her.stats = save; memo.clear(); return r; };
      for (const k of keys) {
        if (k === "stamina") continue; // past her full-spurt need it's worth nothing either way
        const i = keys.indexOf(k), at = her.stats[k];
        const d = [0, 1].flatMap((b) => diff(runStats({ [k]: at + 50 }, b), runStats({}, b)));
        const L = summary(d.map((x) => x[0]));
        const solo = rv ? O.onCurve(rv.curves[i], at + 50, false) - O.onCurve(rv.curves[i], at, false) + O.stepL(rv, i, at + 50) - O.stepL(rv, i, at) : null;
        stats.push([i, 50, +L.m.toFixed(3), +L.ci.toFixed(3), solo == null ? null : +solo.toFixed(3)]);
        process.stderr.write(`${id} ${st} +50 ${k}: field ${L.m.toFixed(3)} ±${L.ci.toFixed(3)}, solo ${solo == null ? "-" : solo.toFixed(3)}\n`);
      }
      const ok = stats.filter((x) => x[4] > 0.02);
      const ratio = ok.length ? ok.reduce((n, x) => n + x[2], 0) / ok.reduce((n, x) => n + x[4], 0) : null;
      cup.styles[st] = { stats, statRatio: ratio == null ? null : +ratio.toFixed(3) };
      continue;
    }
    const candidates = [...new Set(chart(p.id, st).filter(([, med]) => med > 0).map(([sid]) => String(sid)).concat(Object.keys(DEBUFFS)))]
      .filter((sid) => TABLE[sid] && outFor(p)(sid) && F.canFire(F.conditionsOf(TABLE[sid]), p, st));
    const before = (((saved || {}).cups || {})[id] || { styles: {} }).styles[st] || null;
    const skills = Object.assign({}, before && before.skills), list = limit ? candidates.slice(0, limit) : candidates, raw = {};
    const moreDone = new Set((before && before.moreDone) || []);
    let unsupported = 0;
    const keep = (stage) => { cup.styles[st] = { her: lineFor(p, st), build, partial: stage, moreDone: [...moreDone], skills }; checkpoint(); };
    const record = (sid, parts) => {
      const d = parts.flatMap((x) => x.d), fired = parts.flatMap((x) => x.fired);
      const at = fired.map((x) => x.at[sid]).filter((x) => x != null);
      const L = summary(d.map((x) => x[0])), place = summary(d.map((x) => x[1])), win = summary(d.map((x) => x[2]));
      skills[sid] = [+L.m.toFixed(3), +L.ci.toFixed(3), +(at.length / fired.length).toFixed(3), at.length ? Math.round(q(at, 0.1)) : null, at.length ? Math.round(q(at, 0.5)) : null, at.length ? Math.round(q(at, 0.9)) : null, +place.m.toFixed(3), +win.m.toFixed(4), DEBUFFS[sid] ? 1 : 0];
    };
    list.forEach((sid, k) => {
      if (skills[sid]) return; // from the checkpoint
      try { raw[sid] = [value(sid, 0)]; record(sid, raw[sid]); }
      catch (e) { unsupported++; skills[sid] = [null, null, 0, null, null, null, 0, 0, DEBUFFS[sid] ? 1 : 0, String(e.message || e).slice(0, 80)]; }
      if ((k + 1) % 25 === 0) process.stderr.write(`${id} ${st} ${k + 1}/${list.length} ${Math.round((Date.now() - t0) / 1000)}s\n`);
      if ((k + 1) % 10 === 0) keep("first");
    });
    keep("first");
    // The ones that compete for her SP: more races (a new seed block, paired the same way).
    const top = Object.keys(skills).filter((sid) => skills[sid][0] != null).sort((a, b2) => skills[b2][0] - skills[a][0]).slice(0, TOP);
    top.forEach((sid, k) => {
      if (moreDone.has(sid)) return;
      if (!raw[sid]) raw[sid] = [value(sid, 0)]; // resumed: its first races again (same seeds, same result)
      raw[sid].push(value(sid, 1)); record(sid, raw[sid]); moreDone.add(sid);
      if ((k + 1) % 5 === 0) keep("more");
      if ((k + 1) % 10 === 0) process.stderr.write(`${id} ${st} more races ${k + 1}/${top.length} ${Math.round((Date.now() - t0) / 1000)}s\n`);
    });
    const base = run(build, 0);
    const winBase = base.filter((x) => x.place === 0).length / base.length, placeBase = base.reduce((n, x) => n + x.place + 1, 0) / base.length;
    cup.styles[st] = { her: lineFor(p, st), build, base: { win: +winBase.toFixed(3), place: +placeBase.toFixed(2) }, unsupported, more: top, moreDone: [...moreDone], skills };
    checkpoint();
    process.stderr.write(`${id} ${st} done: ${list.length} skills, ${unsupported} unsupported, ${Math.round((Date.now() - t0) / 1000)}s\n`);
  }
  race.close();
}
if (part) checkpoint();
else { const cups = out.cups; write(cups, META({ races: RACES })); }
