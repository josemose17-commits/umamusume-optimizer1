// Which white skills are greens (passive stat skills) and which are recoveries, with the
// conditions that decide whether they fire on a given race, from alpha123's Umalator game data.
// The Parents tab counts the greens that fit a CM race and the recoveries that fit it (Mile and
// longer) as relevant parent skills, even where the Umalator's length gain is small.
// Usage: node tools/build_skill_kinds.js <skill_meta.json> <skill_data.json> <course_data.json>
// (from https://github.com/alpha123/uma-tools/tree/master/umalator-global).
"use strict";
const fs = require("node:fs");
const path = require("node:path");
const [metaFile, dataFile, courseFile] = process.argv.slice(2);
const meta = JSON.parse(fs.readFileSync(metaFile, "utf8"));
const data = JSON.parse(fs.readFileSync(dataFile, "utf8"));
const courses = JSON.parse(fs.readFileSync(courseFile, "utf8"));
// Icon families: 100xx are passive stat skills (greens), 2002x recoveries.
const kindOf = (icon) => (/^100\d\d$/.test(icon) ? "green" : /^2002\d$/.test(icon) ? "recovery" : null);
const skills = {};
Object.keys(meta).sort((a, b) => +a - +b).forEach((id) => {
  const d = data[id], kind = kindOf(String(meta[id].iconId));
  // White skills only (only they become sparks), and no negative (×) versions.
  if (!kind || !d || d.rarity !== 1) return;
  if (d.alternatives.some((a) => a.effects.some((e) => e.modifier < 0))) return;
  // Alternatives are separate ways to fire: any one of them is enough.
  skills[id] = [kind, d.alternatives.map((a) => [a.precondition, a.condition].filter(Boolean).join("&"))];
});
const tracks = {};
Object.keys(courses).forEach((id) => { tracks[id] = courses[id].raceTrackId; });
const out = { meta: { source: "alpha123's Umalator Global game data (skill_meta, skill_data, course_data); game data © Cygames, Inc.", built: new Date().toISOString().slice(0, 10),
  fields: ["kind: green or recovery", "conditions, one per alternative (& = and, @ = or)"] }, skills, tracks };
fs.writeFileSync(path.join(__dirname, "../data/skill-kinds.js"), "// Generated by tools/build_skill_kinds.js. Do not edit. Game data © Cygames, Inc.\n" +
  "(function (root) {\n  const data = " + JSON.stringify(out) + ";\n" +
  "  if (typeof module !== \"undefined\" && module.exports) module.exports = data;\n  else root.UmaSkillKinds = data;\n})(typeof window !== \"undefined\" ? window : globalThis);\n");
console.log("Wrote", Object.keys(skills).length, "green and recovery skills,", Object.keys(tracks).length, "courses");
