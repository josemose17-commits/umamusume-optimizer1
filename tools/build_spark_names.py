#!/usr/bin/env python3
"""Download GameTora's spark (factor) table and write data/spark-names.js.

Run from the repository root:  python3 tools/build_spark_names.py
Needs network access to gametora.com. The output is committed, so the app works offline.

Used to read sparks pasted as text (uma.moe's parent pages): each English name (Global's and
GameTora's, lower-cased with spaces collapsed) maps to
  white: the skill family whose base white the spark hints (e.g. "corner adept ○" -> "20033"),
  green: the trainee versions (card ids) whose unique it is,
  race:  the G1's race id (e.g. "japan c." -> 1019),
  scenario: scenario sparks (known, not scored).
Data source: GameTora (https://gametora.com/umamusume). Game data (c) Cygames, Inc.
"""
import datetime
import json
import os
import re
import unicodedata
import urllib.request

GT = "https://gametora.com"
OUT = os.path.join(os.path.dirname(__file__), "..", "data", "spark-names.js")


def get(url):
    req = urllib.request.Request(url, headers={"User-Agent": "uma-turn-coach data build"})
    with urllib.request.urlopen(req, timeout=60) as r:
        return r.read().decode("utf-8")


def key(name):
    return re.sub(r"\s+", " ", unicodedata.normalize("NFKC", name)).strip().lower()


def names(x):
    return {key(x[k]) for k in ("name_en", "name_en_gl") if x.get(k)}


def main():
    manifest = json.loads(get(GT + "/data/manifests/umamusume.json"))
    factors = json.loads(get("%s/data/umamusume/factors.%s.json" % (GT, manifest["factors"])))
    out = {"white": {}, "green": {}, "race": {}, "scenario": []}
    for x in factors["skill"]:
        for n in names(x):
            out["white"][n] = x["id"]
    for x in factors["other"]:
        if x.get("type") != 3:  # 3: a trainee's unique (green); the rest are event bonuses
            continue
        for n in names(x):
            out["green"].setdefault(n, []).append(int(x["id"]))
    for x in factors["race"]:
        for n in names(x):
            out["race"][n] = int(x["race_id"])
    out["scenario"] = sorted({n for x in factors["scenario"] for n in names(x)})
    meta = {"source": "GameTora (gametora.com) factors", "built": datetime.date.today().isoformat()}
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("// Generated by tools/build_spark_names.py from GameTora (gametora.com). Game data (c) Cygames, Inc.\n")
        f.write("// Spark names (lower-cased, spaces collapsed) -> white skill family, green card ids, G1 race id.\n")
        f.write("(function (root) {\n  const data = ")
        f.write(json.dumps(dict(meta=meta, **out), ensure_ascii=False, separators=(",", ":"), sort_keys=True))
        f.write(";\n  if (typeof module !== \"undefined\" && module.exports) module.exports = data;\n  else root.UmaSparkNames = data;\n})(typeof window !== \"undefined\" ? window : globalThis);\n")
    print("white %d, green %d, race %d, scenario %d" % (len(out["white"]), len(out["green"]), len(out["race"]), len(out["scenario"])))


if __name__ == "__main__":
    main()
