// Realistic rivals for the Skill optimizer's full-field check: what top players actually run, by
// distance, from uma.moe's public statistics (Team Trials rosters of the top team class, class 6,
// aggregated over every scenario). Writes data/rival-pools.js.
//
// Usage:
//   curl -sS https://uma.moe/assets/statistics/datasets.json -o datasets.json
//   (take the newest entry's basePath, e.g. /assets/statistics/2026-11-06)
//   curl -sS https://uma.moe/assets/statistics/2026-11-06/global/global.json.gz -o global.json.gz
//   node tools/build_rival_pools.js global.json.gz 2026-11-06 [<characters dir>]
// With a characters dir (each top-picked uma's <id>.json.gz from
// https://uma.moe/assets/statistics/<version>/characters/<id>.json.gz), each uma also gets her own
// build per distance: her players' 50 most-bought skills, stat percentiles, unique level and
// running-style shares.
'use strict';
const fs = require('fs');
const path = require('path');
const zlib = require('zlib');

const [file, version, charDir] = process.argv.slice(2);
if (!file || !version) throw new Error('usage: build_rival_pools.js <global.json(.gz)> <dataset version>');
const readJson = (f) => { const raw = fs.readFileSync(f); return JSON.parse((raw[0] === 0x1f && raw[1] === 0x8b ? zlib.gunzipSync(raw) : raw).toString('utf8')); };
const g = readJson(file);
const CLASS = '6';
// uma.moe distance ids: 1 sprint, 2 mile, 3 medium, 4 long, 5 dirt.
const NAMES = { 1: 'Sprint', 2: 'Mile', 3: 'Medium', 4: 'Long', 5: 'Dirt' };
const STAT = { speed: 'speed', stamina: 'stamina', power: 'power', guts: 'guts', wisdom: 'wiz' };
const round = (x) => Math.round(x * 1000) / 1000;
const out = { meta: { source: 'uma.moe public statistics (https://uma.moe/statistics), Team Trials rosters of the top team class (class ' + CLASS + '), all scenarios',
  version, generated: g.metadata.generated_at, trainers: g.metadata.total_trainers, classTrainers: g.team_class_distribution[CLASS].count }, distances: {} };
Object.entries(NAMES).forEach(([id, name]) => {
  const o = g.by_distance[id].by_team_class[CLASS].overall, n = o.total_entries;
  const stats = {};
  Object.entries(STAT).forEach(([k, src]) => { const s = o.stat_averages[src]; stats[k] = { p25: Math.round(s.percentiles['25']), p50: Math.round(s.percentiles['50']), p75: Math.round(s.percentiles['75']), p95: Math.round(s.percentiles['95']) }; });
  out.distances[name] = {
    entries: n,
    skillsPerUma: round(o.total_skills / n),
    stats,
    umas: Object.values(o.uma_distribution).sort((a, b) => b.count - a.count).map((u) => [u.id, round(u.count / n)]),
    skills: Object.values(o.skills).sort((a, b) => b.total - a.total).map((s) => [s.id, round(s.total / n)]),
    builds: {},
  };
  if (!charDir) return;
  out.distances[name].umas.forEach(([uid]) => {
    const f = path.join(charDir, uid + '.json.gz');
    if (!fs.existsSync(f)) return;
    const c = readJson(f), cls = ((c.by_distance[id] || {}).by_team_class || {})[CLASS];
    const co = cls && cls.overall;
    if (!co || co.total_entries < 30) return;
    const m = co.total_entries, sk = Object.values(co.common_skills || {}).sort((a, b) => b.total - a.total);
    const uniq = sk.find((x) => /^1\d{5}$/.test(x.id));
    const st = {};
    Object.entries(STAT).forEach(([k, src]) => { const q = co.stat_averages[src]; st[k] = { p25: Math.round(q.percentiles['25']), p50: Math.round(q.percentiles['50']), p75: Math.round(q.percentiles['75']), p95: Math.round(q.percentiles['95']) }; });
    const rs = c.global.running_style_distribution, styles = [1, 2, 3, 4].map((k) => round((rs[k] || { count: 0 }).count / rs.total_entries));
    out.distances[name].builds[uid] = {
      entries: m, skillsPerUma: round(co.total_skills / m), stats: st, styles,
      unique: uniq ? { id: uniq.id, levels: Object.fromEntries(Object.entries(uniq.by_level).map(([lv, k]) => [lv, round(k / uniq.total)])) } : null,
      skills: sk.filter((x) => !/^1\d{5}$/.test(x.id)).map((x) => [x.id, round(x.total / m)]),
    };
  });
});
const target = path.join(__dirname, '..', 'data/rival-pools.js');
fs.writeFileSync(target, `// Generated by tools/build_rival_pools.js from uma.moe's public statistics. Do not edit.
(function (root) {
  const data = ${JSON.stringify(out)};
  if (typeof module !== "undefined" && module.exports) module.exports = data;
  else root.UmaRivalPools = data;
})(typeof window !== "undefined" ? window : globalThis);
`);
console.log('rival pools', version, Object.entries(out.distances).map(([k, d]) => `${k}: ${d.umas.length} umas (${Object.keys(d.builds).length} own builds), ${d.skills.length} skills, ${d.entries} rosters`).join('; '));
