#!/usr/bin/env python3
"""Download the data the parent planner needs and write data/parent-data.js.

Run from the repository root:  python3 tools/build_parent_data.py
Needs network access to gametora.com and daftuyda.moe. The output is committed, so the coach
works offline.

- Affinity groups (succession_relation / succession_relation_member, Global) and the rank
  thresholds (single_mode_rank) come from GameTora (https://gametora.com/umamusume).
- Each skill's rating value, with its aptitude-dependent values, comes from UmaTools' skill
  table (https://daftuyda.moe, data from GameTora and GameWith). Only the numbers are taken;
  rows are matched to GameTora skill ids by English or Japanese name.
Game data (c) Cygames, Inc.
"""
import csv
import datetime
import io
import json
import os
import urllib.request

GT = "https://gametora.com"
UT_SKILLS = "https://daftuyda.moe/assets/uma_skills.csv"
OUT = os.path.join(os.path.dirname(__file__), "..", "data", "parent-data.js")


def get(url):
    req = urllib.request.Request(url, headers={"User-Agent": "uma-turn-coach data build"})
    with urllib.request.urlopen(req, timeout=60) as r:
        return r.read().decode("utf-8")


def gametora(manifest, key):
    return json.loads(get("%s/data/umamusume/%s.%s.json" % (GT, key, manifest[key])))


def num(s):
    return None if s in ("", None) else int(round(float(s)))


def main():
    manifest = json.loads(get(GT + "/data/manifests/umamusume.json"))
    relation = gametora(manifest, "en/db-files/succession_relation")
    members = gametora(manifest, "en/db-files/succession_relation_member")
    ranks = gametora(manifest, "en/db-files/single_mode_rank")
    skills = gametora(manifest, "skills")

    # Affinity: each group gives its points to every pair (and trio) of characters in it.
    by_type = {}
    for m in members:
        by_type.setdefault(m["relation_type"], []).append(m["chara_id"])
    groups = [[r["relation_point"], sorted(set(by_type.get(r["relation_type"], [])))]
              for r in sorted(relation, key=lambda r: r["relation_type"])]
    groups = [g for g in groups if len(g[1]) > 1]

    # Skill rating values. Columns: base value, then the value at S/A, B/C, D/E/F and G
    # aptitude for the skill's role (distance, style or surface); blank when it doesn't vary.
    by_en, by_jp = {}, {}
    for s in skills:
        for k in ("name_en", "enname"):
            if s.get(k):
                by_en.setdefault(s[k], set()).add(s["id"])
        if s.get("jpname"):
            by_jp.setdefault(s["jpname"], set()).add(s["id"])
        g = s.get("gene_version") or {}
        if g.get("id") and s.get("jpname"):
            by_jp.setdefault("gene:" + s["jpname"], set()).add(g["id"])
    rating = {}
    unmatched = []
    for row in csv.DictReader(io.StringIO(get(UT_SKILLS))):
        ids = set(by_en.get(row["name"], set()))
        for alias in row["alias_name"].split("|"):
            ids |= by_jp.get(alias, set())
        if row["skill_type"] == "ius":
            # Inherited uniques: the gene version of the trainee's unique.
            gene = set()
            for alias in row["alias_name"].split("|"):
                gene |= by_jp.get("gene:" + alias, set())
            ids = gene or ids
        if not ids:
            unmatched.append(row["name"])
            continue
        entry = [num(row["base_value"]), num(row["S_A"]), num(row["B_C"]), num(row["D_E_F"]), num(row["G"]),
                 row["affinity_role"] or ""]
        while entry and entry[-1] in (None, ""):
            entry.pop()
        for i in ids:
            rating.setdefault(str(i), entry)

    data = {
        "meta": {"built": datetime.date.today().isoformat(), "source": "GameTora; skill ratings from UmaTools (daftuyda.moe)",
                 "unmatched": len(unmatched)},
        "affinity": groups,
        "ranks": [r["min_value"] for r in sorted(ranks, key=lambda r: r["id"])],
        "skillRating": rating,
    }
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("// Generated by tools/build_parent_data.py from GameTora and UmaTools (daftuyda.moe). Do not edit.\n")
        f.write("// Game data (c) Cygames, Inc.\n(function (root) {\n  const DATA = ")
        f.write(json.dumps(data, separators=(",", ":"), ensure_ascii=False))
        f.write(";\n  if (typeof module !== \"undefined\" && module.exports) module.exports = DATA;\n"
                "  else root.UmaParentData = DATA;\n})(typeof window !== \"undefined\" ? window : globalThis);\n")
    print("affinity groups %d, ranks %d, skill ratings %d, unmatched %d" % (len(groups), len(ranks), len(rating), len(unmatched)))


if __name__ == "__main__":
    main()
