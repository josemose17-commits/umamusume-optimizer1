// Skills only one running style can use: every version of the skill requires running_style==N in
// the simulators' skill data (Global's and JP's). Used to keep game8's picks to her style.
// Usage: node tools/build_skill_styles.js   (writes data/skill-styles.js)
"use strict";
const fs = require("node:fs");
const path = require("node:path");
const ROOT = path.join(__dirname, "..");
const STYLE = { 1: "Nige", 2: "Senkou", 3: "Sasi", 4: "Oikomi" };
const out = {};
["data/race-skills.json", "data/race-skills-jp.json"].forEach((f) => {
  const skills = JSON.parse(fs.readFileSync(path.join(ROOT, f), "utf8")).skills;
  Object.entries(skills).forEach(([id, s]) => {
    const styles = new Set((s.alternatives || []).map((a) => { const m = /running_style==([1-4])/.exec(a.condition || ""); return m ? m[1] : null; }));
    if (styles.size === 1 && !styles.has(null)) out[id] = STYLE[[...styles][0]];
  });
});
const sorted = Object.fromEntries(Object.keys(out).sort((a, b) => a - b).map((k) => [k, out[k]]));
fs.writeFileSync(path.join(ROOT, "data/skill-styles.js"), `// Generated by tools/build_skill_styles.js. Do not edit.
// Skills only one running style can use (every version needs running_style==N): id -> style.
(function (root) {
  const data = ${JSON.stringify(sorted)};
  if (typeof module !== "undefined" && module.exports) module.exports = data;
  else root.UmaSkillStyles = data;
})(typeof window !== "undefined" ? window : globalThis);
`);
console.log(Object.keys(sorted).length + " style skills");
