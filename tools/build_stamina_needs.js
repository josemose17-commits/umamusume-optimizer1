// The stamina each running style needs on each cup's course, from the pinned Umalator
// worker (vendor/umalator): the lowest stamina (in steps of 50) at which her full-last-spurt
// rate is within 2 points of her rate at 2000 stamina (a Front Runner's rate tops out
// below 100%, because rushing costs stamina at random), with the cup's other simulation
// stats, Normal mood, A aptitudes and NO recovery skills (so a heal she buys only adds
// margin). Stamina debuffers in the field are not simulated; the app adds a margin for them.
// Usage: node tools/build_stamina_needs.js [cupId ...]   (writes data/stamina-needs.js)
"use strict";
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");

const ROOT = path.join(__dirname, "..");
const RS = require(path.join(ROOT, "race-skills.js"));
const catalog = JSON.parse(fs.readFileSync(path.join(ROOT, "data/race-skills.json"), "utf8"));
const presetSrc = fs.readFileSync(path.join(ROOT, "data/presets.js"), "utf8");
const PRESETS = JSON.parse(presetSrc.match(/const PRESETS = (\{.*?\});\n/s)[1]);

let handler = null, last = null;
const sandbox = { console: { log() {}, warn() {}, error() {}, assert() {} },
  addEventListener(type, fn) { if (type === "message") handler = fn; }, postMessage(m) { last = m; },
  Math, Date, Map, Set, Array, Object, JSON, Number, String, Symbol, Error, Float64Array, Uint32Array,
  Int32Array, Uint8Array, ArrayBuffer, DataView, BigInt, isNaN, isFinite, parseInt, parseFloat, Infinity, NaN };
sandbox.self = sandbox; sandbox.globalThis = sandbox;
vm.createContext(sandbox);
vm.runInContext(fs.readFileSync(path.join(ROOT, "vendor/umalator/simulator.worker.js"), "utf8"), sandbox);

const RACES = 160, SEED = 4242, SLACK = 0.02, STEP = 50, LOW = 300, HIGH = 2000;
const STYLES = ["Nige", "Senkou", "Sasi", "Oikomi"];

function spurtRate(preset, style, stamina) {
  const s = preset.stats;
  const input = { strategy: style, speed: s.speed, stamina, power: s.power, guts: s.guts, wisdom: s.wisdom, mood: 0 };
  last = null;
  handler({ data: RS.request(preset, input, [], [], catalog, RACES, SEED) });
  if (!last || !last.results) throw new Error("no result");
  return last.results.runData.nspurt[1] / RACES;
}

function need(preset, style) {
  // Smallest multiple of STEP within SLACK of the ceiling (binary search; the spurt rate
  // rises with stamina).
  let lo = LOW / STEP, hi = HIGH / STEP;
  const top = spurtRate(preset, style, hi * STEP), GOAL = top - SLACK;
  if (top < 0.5) return null;
  while (lo < hi) { const mid = Math.floor((lo + hi) / 2); if (spurtRate(preset, style, mid * STEP) >= GOAL) hi = mid; else lo = mid + 1; }
  return lo * STEP;
}

const only = process.argv.slice(2);
const out = {};
const t0 = Date.now();
for (const p of PRESETS.list) {
  if (only.length && !only.includes(p.id)) continue;
  if (!catalog.courses[p.course.id]) continue;
  out[p.id] = {};
  for (const st of STYLES) {
    try { out[p.id][st] = need(p, st); } catch (e) { out[p.id][st] = null; }
  }
  process.stderr.write(`${p.id} ${JSON.stringify(out[p.id])} ${Math.round((Date.now() - t0) / 1000)}s\n`);
}
const meta = { built: new Date().toISOString().slice(0, 10), source: "alpha123's Umalator (pinned Global worker)",
  rule: `lowest stamina (steps of ${STEP}) whose full-spurt rate is within ${SLACK * 100} points of the rate at ${HIGH} stamina, ${RACES} races; cup's simulation stats, Normal mood, A aptitudes, no recovery skills` };
const file = path.join(ROOT, "data/stamina-needs.js");
let prev = {};
if (only.length && fs.existsSync(file)) { const m = fs.readFileSync(file, "utf8").match(/const data = (\{.*\});/s); if (m) prev = JSON.parse(m[1]).cups || {}; }
const data = { meta, cups: Object.assign(prev, out) };
fs.writeFileSync(file, `// Generated by tools/build_stamina_needs.js. Do not edit.
// Stamina each running style needs on each cup's course for a full last spurt (see meta.rule).
(function (root) {
  const data = ${JSON.stringify(data)};
  if (typeof module !== "undefined" && module.exports) module.exports = data;
  else root.UmaStaminaNeeds = data;
})(typeof window !== "undefined" ? window : globalThis);
`);
